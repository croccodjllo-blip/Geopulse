def pairs_for_locale(locale: str) -> list[tuple[str, str]]:
    """Longest Italian source first so short keys cannot eat longer phrases."""
    rows = [(src, table[locale]) for src, table in _PAIRS.items() if locale in table]
    rows.sort(key=lambda item: len(item[0]), reverse=True)
    return rows


def localize_guide_svg(svg: str, locale: str) -> str:
    if locale not in GUIDE_ART_LOCALES:
        return svg
    out = svg
    for src, dst in pairs_for_locale(locale):
        if src != dst:
            out = out.replace(src, dst)
    return out


def localized_guide_rel(rel: str, locale: str) -> str:
    """``img/guide/dashboard.svg`` → ``img/guide/en/dashboard.svg`` when present."""
    name = Path(rel).name
    if locale == "it":
        return rel
    candidate = f"img/guide/{locale}/{name}"
    root = Path(__file__).resolve().parents[1] / "static"
    if (root / candidate).is_file():
        return candidate
    en = f"img/guide/en/{name}"
    if (root / en).is_file():
        return en
    return rel
